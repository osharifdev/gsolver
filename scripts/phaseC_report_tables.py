"""Tables for reports/phaseC.md from the Phase C result files (no computation beyond reading them).

Writes results/phaseC/report_tables.md with, per dataset: every invariant check (count, worst relative margin,
where), and the worst block for every certificate ratio. ChArUco runs record the location of each invariant's
worst case; the reduced (pose-model) runs record only the worst margin of the covariance checks, so their
locations are recovered here from the per-(pose, iteration, K) CSV for the certificate checks and ratios.

Usage: python3 scripts/phaseC_report_tables.py
"""

import csv
import gzip
import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "results" / "phaseC"
CHARUCO = ["charuco_islam_025", "charuco_islam_050", "charuco_islam_100", "charuco_ba_init", "charuco_ba_end"]
REDUCED = ["kitti06_prefix_conv", "kitti06_prefix_init", "kitti06_full_conv"]


def g(x, f="%.3g"):
    return "–" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f % x


def charuco(lines):
    for n in CHARUCO:
        d = json.loads((OUT / n / "summary.json").read_text())
        lines.append("\n### %s: invariants (%d checks, %d failed)\n" % (n, len(d["invariants"]), sum(not r["ok"] for r in d["invariants"])))
        lines.append("| check | n | worst relative margin (≤ 1e-9 passes) | where |\n|---|---|---|---|")
        for r in d["invariants"]:
            lines.append("| %s | %d | %s | %s |" % (r["check"], r["n"], g(r["worst"], "%.2e"), r.get("where", "") or "–"))
        lines.append("\nWorst blocks by ratio (entries with error > 10 × pose floor %.2e):\n" % d["gate"]["pose_floor"])
        lines.append("| certificate | block | kind | iteration | ratio | E | true error | degree |\n|---|---|---|---|---|---|---|---|")
        for k, w in d["worst"].items():
            if k == "largest_err_last_iter":
                continue
            lines.append("| %s | %s | %s | %d | %s | %s | %s | %d |" % (k, w["block"], w["kind"], w["iter"], g(w["ratio"]), g(w["E"]), g(w["err"]), w["degree"]))
        w = d["worst"]["largest_err_last_iter"]
        lines.append("\nLargest true error at the last iteration: %s (%s), %.3e at iteration %d." % (w["block"], w["kind"], w["err"], w["iter"]))


def reduced(lines):
    for n in REDUCED:
        d = json.loads((OUT / "reduced" / ("%s.json" % n)).read_text())
        floor = d["floor"]["floor"]
        rows = list(csv.DictReader(gzip.open(OUT / "reduced" / ("%s_certs.csv.gz" % n), "rt")))
        blocks = sorted({r["block_id"] for r in rows}, key=lambda s: float(s.split("_")[1]))
        pidx = {b: k for k, b in enumerate(blocks)}
        lines.append("\n### %s (pose model, %d poses): invariants (%d checks, %d failed)\n" % (
            n, d["n_blocks"], len(d["checks"]), sum(not c["ok"] for c in d["checks"])))
        lines.append("| check | n | worst relative margin (≤ 1e-9 passes) |\n|---|---|---|")
        for c in d["checks"]:
            lines.append("| %s | %d | %s |" % (c["check"], c["n"], g(c["worst"], "%.2e")))
        lines.append("\nWorst blocks (pose floor %.3e; ratios over entries with error > 10 × floor):\n" % floor)
        lines.append("| K | worst ratio: pose (index), iteration, E / err = ratio | closest to violation of E ≥ err: pose, iteration, (err − E)/E |\n|---|---|---|")
        for K in sorted({int(r["K"]) for r in rows}):
            R = [r for r in rows if int(r["K"]) == K]
            err = np.array([float(r["err_true"]) for r in R])
            E = np.array([float(r["E_C3"]) for r in R])
            gate = (err > 10 * floor) & (err >= 1e-12)
            rat = np.where(gate, E / np.where(err > 0, err, 1), np.nan)
            k = int(np.nanargmax(rat))
            m = (err - E) / np.maximum(E, 1e-300)
            j = int(np.argmax(m))
            lines.append("| %d | %s (%d), %s, %s / %s = %s | %s (%d), %s, %.2e |" % (
                K, R[k]["block_id"], pidx[R[k]["block_id"]], R[k]["iter"], g(E[k]), g(err[k]), g(rat[k]),
                R[j]["block_id"], pidx[R[j]["block_id"]], R[j]["iter"], m[j]))


def main():
    lines = ["# Phase C tables (generated by scripts/phaseC_report_tables.py)", "", "## ChArUco (certified model, brief's certificates)"]
    charuco(lines)
    lines += ["", "## Stereo, landmark-marginalized pose model (scripts/phaseC_reduced.py)"]
    reduced(lines)
    (OUT / "report_tables.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
